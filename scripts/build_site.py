    if rd.exists():
        for d in sorted(rd.iterdir(), reverse=True):
            if not d.is_dir():
                continue
            score = None
            sp = d / "local_score.log"
            if sp.exists():
                score = sp.read_text().strip().splitlines()[0] if sp.read_text().strip() else None
            ev["runs"].append({
                "summary": load(d / "run_summary.json") or {},
                "history": load(d / "train_history.json"),
                "score": score,
                "blend": load(d / "blend_report.json"),
            })

    DOCS.mkdir(exist_ok=True)
    (DOCS / "style.css").write_text(CSS)
    pages = {
        "index.html": build_index(ev),
        "data.html": build_data(ev),
        "metric.html": build_metric(ev),
        "method.html": build_method(ev),
        "results.html": build_results(ev),
        "sources.html": build_sources(ev),
        "reproduce.html": build_reproduce(ev),
    }
    for name, content in pages.items():
        (DOCS / name).write_text(content)
        print(f"wrote docs/{name} ({len(content):,} bytes)")

    have = [k for k, v in ev.items() if v]
    print(f"\nevidence present: {', '.join(have)}")
    absent = [k for k, v in ev.items() if not v]
    if absent:
        print(f"evidence MISSING (sections will say so): {', '.join(absent)}")
    return 0


