def note(kind: str, text: str) -> str:
    return f'<div class="note {kind}">{text}</div>'


def missing(what: str, how: str) -> str:
    return note("warn", f"<strong>Not available.</strong> {e(what)} <br>Produce it with: <code>{e(how)}</code>")


