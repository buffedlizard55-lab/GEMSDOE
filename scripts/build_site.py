"""Generate the GitHub Pages site FROM the machine-generated evidence files.

Anti-hallucination design: the site is not hand-written prose about what the data
supposedly contains. Every number, band name, file size, checksum and link status is
read out of the JSON that a GitHub runner produced by measuring the actual bytes:

    data/evidence/inventory.json        sizes + sha256 + magic of every competition file
    data/evidence/rasters.json          CRS/bounds/res/dtype + per-band tags and stats
    data/evidence/labels_summary.json   label positives + value histogram
    data/evidence/transfer_analysis.json sample-vs-labels cross-check, encoding sizes
    data/evidence/metric_strategy.json  measured DTI baselines
    data/evidence/rules_quotes.json     verbatim quotations from the official rules PDF
    data/dem_links.json                 DEM tiles confirmed against the USGS bucket
    docs/link_verification.json         live HTTP status of every catalog link
    data/evidence/runs/*/               training run reports

If an evidence file is missing, the corresponding section says so explicitly rather
than inventing content. Run:  python scripts/build_site.py
"""
